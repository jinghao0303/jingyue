def import_cities():
    """导入所有城市数据"""
    try:
        conn = pymysql.connect(**DB_CONFIG)
        cursor = conn.cursor()
        
        print("=" * 60)
        print("开始导入全国主要城市数据")
        print("=" * 60)
        
        imported_count = 0
        updated_count = 0
        
        for province_code, city_code, city_name, lat, lng, population in CITIES_DATA:
            try:
                # 1. 确保省份存在
                cursor.execute("SELECT id FROM provinces WHERE province_code = %s", (province_code,))
                province = cursor.fetchone()
                if not province:
                    print(f"⚠️  省份代码 {province_code} 不存在，跳过城市 {city_name}")
                    continue
                
                province_id = province[0]
                
                # 2. 插入或更新城市
                cursor.execute("""
                    INSERT INTO cities (city_code, city_name, province_id, latitude, longitude, status)
                    VALUES (%s, %s, %s, %s, %s, 1)
                    ON DUPLICATE KEY UPDATE
                        city_name = VALUES(city_name),
                        province_id = VALUES(province_id),
                        latitude = VALUES(latitude),
                        longitude = VALUES(longitude),
                        status = 1,
                        updated_at = CURRENT_TIMESTAMP
                """, (city_code, city_name, province_id, lat, lng))
                
                if cursor.rowcount == 1:
                    imported_count += 1
                    print(f"✓ 导入城市: {city_name}")
                else:
                    updated_count += 1
                    print(f"✓ 更新城市: {city_name}")
                
                # 3. 获取城市ID
                cursor.execute("SELECT id FROM cities WHERE city_code = %s", (city_code,))
                city = cursor.fetchone()
                if city:
                    city_id = city[0]
                    
                    # 4. 插入或更新人口数据
                    cursor.execute("""
                        INSERT INTO city_population (city_id, total_population, population_year, data_source, status)
                        VALUES (%s, %s, 2023, '模拟数据', 1)
                        ON DUPLICATE KEY UPDATE
                            total_population = VALUES(total_population),
                            updated_at = CURRENT_TIMESTAMP
                    """, (city_id, population))
                
                conn.commit()
                
            except Exception as e:
                print(f"✗ {city_name}: 导入失败 - {e}")
                conn.rollback()
                continue
        
        print("\n" + "=" * 60)
        print(f"导入完成！")
        print(f"  新增城市: {imported_count} 个")
        print(f"  更新城市: {updated_count} 个")
        print(f"  总计: {imported_count + updated_count} 个城市")
        print("=" * 60)
        
        # 统计
        cursor.execute("SELECT COUNT(*) FROM cities WHERE status = 1")
        total = cursor.fetchone()[0]
        print(f"\n数据库中启用状态的城市总数: {total} 个")
        
        cursor.close()
        conn.close()
        
    except Exception as e:
        print(f"✗ 导入失败: {e}")
        import traceback
        traceback.print_exc()


if __name__ == '__main__':
    import_cities()

